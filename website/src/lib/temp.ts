// Temperature → color on the Thermal Night scale (DESIGN.md temp-13 … temp-43), clamped to 13–43 °C.
// Interpolates in OKLab between the five stops: perceptually even, and the cyan→amber leg passes through the
// neutral stop instead of sweeping through green. Used by build-time SVGs and by the hero island.

const STOPS: [number, [number, number, number]][] = [
  [13, [0.6872, -0.0416, -0.1618]], // #4C9BFF
  [20, [0.8102, -0.0910, -0.0673]], // #5CD3F0
  [28, [0.9122, -0.0093, -0.0141]], // #D8E4EC
  [36, [0.8245, 0.0426, 0.1424]], // #FFB547
  [43, [0.7591, 0.1020, 0.1213]], // #FF8F4A
];

export function tempColor(c: number): string {
  const t = Math.min(43, Math.max(13, c));
  let k = 0;
  while (k < STOPS.length - 2 && t > STOPS[k + 1][0]) k++;
  const [t0, a] = STOPS[k];
  const [t1, b] = STOPS[k + 1];
  const f = (t - t0) / (t1 - t0);
  const v = a.map((x, i) => (x + (b[i] - x) * f).toFixed(4));
  return `oklab(${v[0]} ${v[1]} ${v[2]})`;
}

export const fmtC = (c: number, digits = 1) => `${c.toFixed(digits)} °C`;

/** Contents of src/styles/temp-scale.css (generated by scripts/gen-temp-css.mjs). */
export function tempCss(): string {
  const out = ["/* GENERATED by scripts/gen-temp-css.mjs from src/lib/temp.ts. Do not edit. */"];
  for (let c = 13; c <= 43; c++) out.push(`.tc-${c} { color: ${tempColor(c)}; }`);
  const dawnRules = (sel: string) => [
    `${sel} [class^="tc-"], ${sel} [class*=" tc-"] { color: var(--warm); }`,
    Array.from({ length: 15 }, (_, k) => `${sel} .tc-${13 + k}`).join(", ") + " { color: var(--cold); }",
  ];
  out.push(`@media (prefers-color-scheme: light) {`, ...dawnRules(`:root:not([data-theme="dark"])`).map((l) => "  " + l), "}");
  out.push(...dawnRules(`:root[data-theme="light"]`));
  return out.join("\n") + "\n";
}

/** Class name for a temperature readout: tc-13 … tc-43. */
export const tempClass = (c: number) => `tc-${Math.min(43, Math.max(13, Math.round(c)))}`;
